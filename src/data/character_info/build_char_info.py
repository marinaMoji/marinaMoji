"""Builds char_info.tsv from a Unicode Unihan unzip for the character composer.

Display-only metadata (readings, strokes, variants, gloss). Drawing data stays
in data/kage/; IDS lookup stays in data/character_composer/.

    python3 build_char_info.py --unihan /path/to/Unihan --out char_info.tsv
"""

from __future__ import annotations

import argparse
import collections
import pathlib
import re
import sys

# Same coverage as data/kage/build_kage_data.py when --composer-blocks is set.
COMPOSER_BLOCKS = [
    (0x2E80, 0x2FDF),
    (0x3040, 0x30FF),
    (0x3400, 0x4DBF),
    (0x4E00, 0x9FFF),
    (0xF900, 0xFAFF),
]

CP_RE = re.compile(r'^U\+([0-9A-Fa-f]{4,6})$')

# field -> which Unihan file usually holds it (any file may be scanned).
FIELDS = {
    'kTotalStrokes': 'strokes',
    'kMandarin': 'pinyin',
    'kJapaneseOn': 'ja_on',
    'kJapaneseKun': 'ja_kun',
    'kRSUnicode': 'rs',
    'kDefinition': 'definition',
}

VARIANT_FIELDS = (
    'kZVariant',
    'kSemanticVariant',
    'kTraditionalVariant',
    'kSimplifiedVariant',
    'kCompatibilityVariant',
    'kSpecializedSemanticVariant',
)


def parse_cp(token: str) -> int | None:
    m = CP_RE.match(token.strip())
    return int(m.group(1), 16) if m else None


def load_unihan(directory: pathlib.Path) -> dict[int, dict[str, str]]:
    """Map code point -> {column_name: value} from every Unihan_*.txt in |directory|."""
    rows: dict[int, dict[str, str]] = collections.defaultdict(dict)
    files = sorted(directory.glob('Unihan_*.txt'))
    if not files:
        raise SystemExit(f'no Unihan_*.txt under {directory}')

    for path in files:
        with path.open(encoding='utf-8') as f:
            for line in f:
                if not line or line.startswith('#'):
                    continue
                parts = line.rstrip('\n').split('\t')
                if len(parts) < 3:
                    continue
                cp_s, field, value = parts[0], parts[1], parts[2]
                cp = parse_cp(cp_s)
                if cp is None:
                    continue
                if field in FIELDS:
                    col = FIELDS[field]
                    # First wins for multi-file duplicates; Unihan is consistent.
                    rows[cp].setdefault(col, value)
                elif field in VARIANT_FIELDS:
                    chars = []
                    for token in value.replace(',', ' ').split():
                        # Values look like "U+4E00<kMatthews>" or plain "U+4E00".
                        head = token.split('<', 1)[0]
                        other = parse_cp(head)
                        if other is not None:
                            try:
                                chars.append(chr(other))
                            except ValueError:
                                pass
                    if chars:
                        prev = rows[cp].get('variants', '')
                        merged = []
                        for c in (prev.split() if prev else []) + chars:
                            if c not in merged:
                                merged.append(c)
                        rows[cp]['variants'] = ' '.join(merged)
    return rows


def first_strokes(raw: str) -> str:
    # kTotalStrokes can be "10" or "10 11" (source disagreement); take the first.
    return raw.split()[0] if raw else ''


def in_composer_blocks(cp: int) -> bool:
    return any(lo <= cp <= hi for lo, hi in COMPOSER_BLOCKS)


def write_tsv(rows: dict[int, dict[str, str]], out: pathlib.Path,
              composer_blocks: bool) -> int:
    columns = ('char', 'cp', 'strokes', 'pinyin', 'ja_on', 'ja_kun', 'rs',
               'definition', 'variants')
    n = 0
    with out.open('w', encoding='utf-8', newline='\n') as f:
        f.write('# Character display info for the marinaMoji character composer.\n')
        f.write('# Generated by build_char_info.py from Unicode Unihan. See README.md.\n')
        f.write('#' + '\t'.join(columns) + '\n')
        for cp in sorted(rows):
            if composer_blocks and not in_composer_blocks(cp):
                continue
            try:
                ch = chr(cp)
            except ValueError:
                continue
            info = rows[cp]
            # Skip code points that have none of the useful fields.
            if not any(info.get(c) for c in columns if c not in ('char', 'cp')):
                continue
            cells = {
                'char': ch,
                'cp': f'U+{cp:04X}',
                'strokes': first_strokes(info.get('strokes', '')),
                'pinyin': info.get('pinyin', ''),
                'ja_on': info.get('ja_on', ''),
                'ja_kun': info.get('ja_kun', ''),
                'rs': info.get('rs', ''),
                'definition': info.get('definition', ''),
                'variants': info.get('variants', ''),
            }
            f.write('\t'.join(cells[c] for c in columns) + '\n')
            n += 1
    return n


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--unihan', type=pathlib.Path, required=True,
                    help='directory containing Unihan_*.txt')
    ap.add_argument('--out', type=pathlib.Path, required=True)
    ap.add_argument('--composer-blocks', action='store_true',
                    help='only BMP radicals/kana/CJK blocks the composer draws')
    args = ap.parse_args()

    rows = load_unihan(args.unihan)
    n = write_tsv(rows, args.out, args.composer_blocks)
    print(f'{n} characters -> {args.out}', file=sys.stderr)


if __name__ == '__main__':
    main()
